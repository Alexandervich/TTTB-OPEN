// Class advancement tables from the Tod & Teufel house rules (TTTB.pdf, section 2), levels 1-20.
// Saves are [Doom, Ray, Hold, Blast, Spell]; they are stored in the death/magic/paralysis/breath/spell columns.

const LEVELS = 20

// Expands [[fromLevel, value], ...] into one value per level.
function bands(entries) {
  return Array.from({ length: LEVELS }, (_, index) => {
    const level = index + 1
    return [...entries].reverse().find(([from]) => level >= from)[1]
  })
}

const flatHp = (perLevel) => Array.from({ length: LEVELS }, (_, i) => Math.max(0, i + 1 - 9) * perLevel)

